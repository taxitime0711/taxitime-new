import assert from "node:assert/strict";
import {quoteDriverOffer, initialAccount, completeOrderCommission, topUpDeposit} from "./finance.mjs";
assert.deepEqual(quoteDriverOffer(70), {driverPrice:70,commission:7,passengerPrice:77});
assert.deepEqual(quoteDriverOffer(0.01), {driverPrice:0.01,commission:0,passengerPrice:0.01});
let a = topUpDeposit(initialAccount(), 20).account;
let first = completeOrderCommission(a, "ORDER-1", 7);
assert.equal(first.account.depositCents, 1300);
assert.equal(first.account.debtCents, 0);
let repeat = completeOrderCommission(first.account, "ORDER-1", 7);
assert.equal(repeat.charged, false);
assert.equal(repeat.account.depositCents, 1300);
let second = completeOrderCommission(repeat.account, "ORDER-2", 20);
assert.equal(second.account.depositCents, 0);
assert.equal(second.account.debtCents, 700);
let refill = topUpDeposit(second.account, 10);
assert.equal(refill.account.debtCents, 0);
assert.equal(refill.account.depositCents, 300);
assert.equal(refill.debtRepaid, 7);
assert.throws(() => quoteDriverOffer(-1));
assert.throws(() => topUpDeposit(initialAccount(), 0));
console.log("TAXI TIME finance tests: PASS");
